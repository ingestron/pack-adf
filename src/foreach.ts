// pattern: foreach: one pipeline per connection and database, with one
// parameterised Copy inside a ForEach over the pipeline's tables parameter.
// The parameter's default value is the generated table list, so nothing is
// read at run time; a run can pass a shorter list to copy some tables again.
import type { ResolvedModel, ResolvedTable } from "@ingestron/definitions";
import { activity, additionalColumnsOf, describePipeline, policyOf } from "./design.js";
import { staticFile } from "./layout.js";
import { selectOf, watermarkOf } from "./query.js";
import { reference, type CopyGroup, type Shared } from "./resources.js";
import { sqlTypes } from "./sql-types.js";

type Data = Record<string, unknown>;

const expression = (value: string) => ({ value, type: "Expression" });
const at = (name: string) => `formatDateTime(pipeline().parameters.${name}, 'yyyy-MM-dd HH:mm:ss')`;

/** The item's query, with the window filter when the item names a watermark column. */
const queryExpression =
  "@{item().query}@{if(empty(item().watermark), '', concat(' WHERE ', item().watermark, " +
  `' >= ''', ${at("windowStart")}, ''' AND ', item().watermark, ' < ''', ${at("windowEnd")}, ''''))}`;

/** The item's file, or a new file per run named by the window's start and the run. */
const fileExpression =
  "@{if(empty(item().file), concat(formatDateTime(pipeline().parameters.windowStart, " +
  "'yyyyMMddHHmmss'), '_', pipeline().RunId, '.parquet'), item().file)}";

/** One table's entry in the tables parameter: everything its copy needs, as plain text. */
export function itemOf(table: ResolvedTable): Data {
  const landed = staticFile(table, "parquet")!;
  return {
    table: table.name,
    object: table.ingest!.object,
    connection: table.ingest!.connection.id,
    query: selectOf(table),
    watermark: watermarkOf(table),
    folder: landed.folder,
    file: landed.file,
  };
}

/** The connection's pipeline: a ForEach over its tables, copying each with one Copy. */
export function foreachPipeline(
  model: ResolvedModel,
  group: CopyGroup,
  shared: Shared,
  name: string,
): Data {
  const parallel = (group.tables[0]!.ingest!.settings.parallel as number | undefined) ?? 4;
  return {
    name,
    properties: {
      description: describePipeline(
        group.tables,
        "one Copy activity inside a ForEach over the tables parameter",
      ),
      activities: [
        {
          name: "for_each_table",
          description: `Copies each table in the tables parameter, ${parallel} at a time.`,
          type: "ForEach",
          typeProperties: {
            items: expression("@pipeline().parameters.tables"),
            isSequential: false,
            batchCount: parallel,
            activities: [copyTable(group, shared)],
          },
        },
      ],
      parameters: {
        windowStart: { type: "string" },
        windowEnd: { type: "string" },
        tables: { type: "array", defaultValue: group.tables.map(itemOf) },
      },
      annotations: [`Generated by Ingestron from the ${model.project.id} definitions`],
    },
  };
}

/** The Copy inside the ForEach, reading the current item; its tables share policy and audit columns. */
function copyTable(group: CopyGroup, shared: Shared): Data {
  const first = group.tables[0]!;
  return activity(
    "copy_table",
    "Copies the current table to landing as Parquet.",
    "Copy",
    {
      inputs: [reference(group.dataset, "DatasetReference")],
      outputs: [
        {
          ...reference(shared.landingDataset, "DatasetReference"),
          parameters: { folder: expression("@item().folder"), file: expression(fileExpression) },
        },
      ],
      typeProperties: {
        source: {
          type: sqlTypes[group.connection.connector]!.source,
          sqlReaderQuery: expression(queryExpression),
          ...additionalColumnsOf(first, true),
        },
        sink: {
          type: "ParquetSink",
          storeSettings: { type: "AzureBlobFSWriteSettings" },
          formatSettings: { type: "ParquetWriteSettings" },
        },
      },
    },
    policyOf(first),
  );
}
