// ADF resources as data, in the JSON shape ADF keeps in Git:
// { "name": …, "properties": { … } }.
import { resourceName } from "./resource-names.js";
import type { ResolvedModel, ResolvedTable } from "@ingestron/definitions";
import { parseLanding } from "./landing.js";
import { landedFile } from "./layout.js";
import { sqlTypes } from "./sql-types.js";
import { sqlCredentials } from "./sql-auth.js";
import { query } from "./query.js";

type Data = Record<string, unknown>;

/** The tables one connection and database copy, with the names of their resources. */
export interface CopyGroup {
  connection: NonNullable<ResolvedTable["ingest"]>["connection"];
  database: string;
  tables: ResolvedTable[];
  linkedService: string;
  dataset: string;
}

/** Names shared by every group of a project. */
export interface Shared {
  keyVault: string;
  landing: string;
  landingDataset: string;
  /** The landing folder for files copied as they are. */
  landingFiles: string;
  /** The binary landing dataset with a parameterised HTTP filename. */
  landingHttp: string;
}

/** A reference to another ADF resource by name. */
export const reference = (name: string, type: string) => ({ referenceName: name, type });

/** The Key Vault linked service; secrets are referenced from it. */
export function keyVaultService(shared: Shared, baseUrl: string): Data {
  return {
    name: shared.keyVault,
    properties: { type: "AzureKeyVault", typeProperties: { baseUrl } },
  };
}

/** The landing storage, reached with the factory's managed identity. */
export function landingService(shared: Shared, landing: string): Data {
  return {
    name: shared.landing,
    properties: { type: "AzureBlobFS", typeProperties: { url: parseLanding(landing).url } },
  };
}

/** The SQL Server, through the self-hosted integration runtime. */
export function sqlServerService(group: CopyGroup, shared: Shared, settings: Data): Data {
  const connection = group.connection.settings;
  return {
    name: group.linkedService,
    properties: {
      type: sqlTypes[group.connection.connector]!.service,
      typeProperties: {
        server: connection.server,
        database: group.database,
        encrypt: settings.encrypt,
        trustServerCertificate: false,
        ...sqlCredentials(connection, shared.keyVault),
        ...(Boolean(connection.host_name_in_certificate) && {
          hostNameInCertificate: connection.host_name_in_certificate,
        }),
      },
      connectVia: reference(String(settings.integration_runtime), "IntegrationRuntimeReference"),
    },
  };
}

/** The source dataset; each copy reads with its own query. */
export function sourceDataset(group: CopyGroup): Data {
  return {
    name: group.dataset,
    properties: {
      type: sqlTypes[group.connection.connector]!.dataset,
      linkedServiceName: reference(group.linkedService, "LinkedServiceReference"),
    },
  };
}

/** One Parquet dataset for the landing folder; each copy passes its folder and file. */
export function landingDataset(shared: Shared, landing: string): Data {
  const { fileSystem } = parseLanding(landing);
  const expression = (name: string) => ({ value: `@dataset().${name}`, type: "Expression" });
  return {
    name: shared.landingDataset,
    properties: {
      type: "Parquet",
      linkedServiceName: reference(shared.landing, "LinkedServiceReference"),
      parameters: { folder: { type: "string" }, file: { type: "string" } },
      typeProperties: {
        location: {
          type: "AzureBlobFSLocation",
          fileSystem,
          folderPath: expression("folder"),
          fileName: expression("file"),
        },
        compressionCodec: "snappy",
      },
    },
  };
}

/** A Copy activity per table, all in one pipeline per connection and database. */
export function copyPipeline(
  model: ResolvedModel,
  group: CopyGroup,
  shared: Shared,
  name: string,
): Data {
  const activities = group.tables.map((table) => copyActivity(table, group, shared));
  const parameters = { windowStart: { type: "string" }, windowEnd: { type: "string" } };
  return {
    name,
    properties: {
      activities,
      parameters,
      annotations: [`Generated by Ingestron from the ${model.project.id} definitions`],
    },
  };
}

function copyActivity(table: ResolvedTable, group: CopyGroup, shared: Shared): Data {
  return {
    name: resourceName(table, "copy_activity", `copy_${table.name}`),
    type: "Copy",
    inputs: [reference(group.dataset, "DatasetReference")],
    outputs: [
      {
        ...reference(shared.landingDataset, "DatasetReference"),
        parameters: landedFile(table, "parquet"),
      },
    ],
    typeProperties: {
      source: { type: sqlTypes[group.connection.connector]!.source, sqlReaderQuery: query(table) },
      sink: {
        type: "ParquetSink",
        storeSettings: { type: "AzureBlobFSWriteSettings" },
        formatSettings: { type: "ParquetWriteSettings" },
      },
    },
  };
}

/**
 * A tumbling window trigger. It is stopped when `paused` says so, else when
 * the platform's schedule is paused, else outside production.
 */
export function windowTrigger(
  model: ResolvedModel,
  group: { tables: ResolvedTable[] },
  pipeline: string,
  name: string,
): Data {
  const settings = group.tables[0]!.ingest!.settings;
  const every = settings.every as { frequency: string; interval: number };
  return {
    name,
    properties: {
      type: "TumblingWindowTrigger",
      runtimeState: paused(model, settings) ? "Stopped" : "Started",
      typeProperties: {
        frequency: every.frequency,
        interval: every.interval,
        startTime: settings.start,
        maxConcurrency: 1,
        retryPolicy: { count: settings.retries, intervalInSeconds: 300 },
      },
      pipeline: {
        pipelineReference: reference(pipeline, "PipelineReference"),
        parameters: {
          windowStart: "@trigger().outputs.windowStartTime",
          windowEnd: "@trigger().outputs.windowEndTime",
        },
      },
    },
  };
}

/** Whether the trigger stays stopped: its own setting, else the platform's schedule, else not in production. */
export function paused(model: ResolvedModel, settings: Record<string, unknown>): boolean {
  if (typeof settings.paused === "boolean") return settings.paused;
  return model.platform.schedule?.paused ?? model.platform.mode !== "production";
}
