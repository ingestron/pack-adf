// Name overrides use ordinary resolved method settings; defaults remain in their builders.
import type { Method, ResolvedTable } from "@ingestron/definitions";
const descriptions = {
  key_vault_linked_service: "Shared Key Vault linked service. Default: ls_<project>_keyvault.",
  landing_linked_service:
    "Shared managed-identity landing linked service. Default: ls_<project>_landing.",
  landing_dataset: "Shared Parquet landing dataset. Default: ds_<project>_landing.",
  landing_files_dataset: "Shared binary landing dataset. Default: ds_<project>_landing_files.",
  landing_http_dataset:
    "Shared HTTP binary landing dataset. Default: ds_<project>_landing_files_http.",
  source_linked_service:
    "Source linked service, shared per connection (and SQL database). Default: ls_<project>_<connection>[_<database>].",
  source_dataset:
    "Source dataset, per native table or shared per SQL database/file connection. Default: ds_<project>_<connection>[_<database> or _<table>].",
  pipeline:
    "Pipeline shared per connection (and SQL database). Default: pl_<project>_<connection>[_<database when different from connection>].",
  trigger:
    "Window trigger shared with the pipeline. Default: tr_<project>_<connection>[_<database when different from connection>].",
  staging_linked_service:
    "Snowflake or Delta staging service. Default: ls_<project>_<connection>_staging.",
  json_landing_linked_service:
    "Microsoft 365 application landing service. Default: ls_<project>_<connection>_json.",
  json_landing_dataset:
    "Microsoft 365 JSON landing dataset. Default: ds_<project>_<connection>_json.",
  copy_activity:
    "Copy activity per table. Default: copy_<table>. Must be unique within its pipeline.",
};
type NameRole = keyof typeof descriptions;
// ASCII names of this length keep the generated .json filenames portable.
const maximumNameLength = 200;
const pattern = (role: string) =>
  ["pipeline", "trigger", "copy_activity"].includes(role)
    ? "^[A-Za-z][A-Za-z0-9_-]*$"
    : "^[A-Za-z][A-Za-z0-9_]*$";
/** Explicit resource-name overrides; ordinary YAML references and settings precedence apply. */
export const resourceNamesSchema: Method["settings"] = {
  type: "object",
  additionalProperties: false,
  description:
    "Optional reusable ADF naming preset. Omitted roles use project/source/table defaults; shared names must agree. Known roles for resources not generated by this source are unused. Values use existing ${project.id}, ${environment.name} and ${values.…} references.",
  properties: Object.fromEntries(
    Object.entries(descriptions).map(([role, description]) => [
      role,
      {
        type: "string",
        minLength: 1,
        maxLength: maximumNameLength,
        pattern: pattern(role),
        description: `${description} Start with a letter; use letters, digits or underscores${["pipeline", "trigger", "copy_activity"].includes(role) ? ", or hyphens" : ""}; at most ${maximumNameLength} characters.`,
        examples: [`custom_${role}`],
      },
    ]),
  ),
};
/** Resolve one resource name, rejecting disagreement among its owning tables. */
export function resourceName(
  tables: ResolvedTable | ResolvedTable[],
  role: NameRole,
  fallback: string,
): string {
  const owners = Array.isArray(tables) ? tables : [tables];
  if (owners.length === 0) return fallback;
  const names = owners.map(
    (table) =>
      (table.ingest!.settings.resource_names as Record<string, string> | undefined)?.[role] ??
      fallback,
  );
  const name = names[0] ?? fallback;
  if (names.some((value) => value !== name))
    throw new Error(
      `ADF resource_names.${role} must agree for tables sharing this resource: ${owners.map((table) => table.name).join(", ")}`,
    );
  if (!new RegExp(pattern(role)).test(name) || name.length > maximumNameLength)
    throw new Error(
      `ADF resource_names.${role} gives invalid name "${name}"; use a letter followed by letters, digits or underscores${["pipeline", "trigger", "copy_activity"].includes(role) ? ", or hyphens" : ""}, at most ${maximumNameLength} characters`,
    );
  return name;
}
