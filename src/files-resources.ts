// ADF resources for adf-files: the share, a binary copy per table and the
// landing folder the files keep their names and folders in.
import { resourceName } from "./resource-names.js";
import {
  nativeFileService,
  nativeFileLocation,
  nativeFileParameters,
} from "./native-file-resources.js";
import { fileStores } from "./file-sources.js";
import type { ResolvedModel, ResolvedTable } from "@ingestron/definitions";
import { parseLanding } from "./landing.js";
import { reference, type Shared } from "./resources.js";

type Data = Record<string, unknown>;

/** The tables one share copies, with the names of its resources. */
export interface FilesGroup {
  connection: NonNullable<ResolvedTable["ingest"]>["connection"];
  tables: ResolvedTable[];
  linkedService: string;
  dataset: string;
}

const folderParameter = { value: "@dataset().folder", type: "Expression" };

/** The share, through the self-hosted integration runtime, with the password from Key Vault. */
export function fileServerService(group: FilesGroup, shared: Shared, settings: Data): Data {
  if (group.connection.connector !== "files") return nativeFileService(group, shared, settings);
  const connection = group.connection.settings;
  const password = connection.password as { $secret: string };
  return {
    name: group.linkedService,
    properties: {
      type: "FileServer",
      typeProperties: {
        host: connection.path,
        userId: connection.user,
        password: {
          type: "AzureKeyVaultSecret",
          store: reference(shared.keyVault, "LinkedServiceReference"),
          secretName: password.$secret,
        },
      },
      connectVia: reference(String(settings.integration_runtime), "IntegrationRuntimeReference"),
    },
  };
}

/** A folder of the share; each copy passes its own. */
export function shareDataset(group: FilesGroup): Data {
  const source = fileStores.find((item) => item.id === group.connection.connector);
  return binaryDataset(
    group.dataset,
    group.linkedService,
    source
      ? nativeFileLocation(source.id)
      : {
          type: "FileServerLocation",
          folderPath: folderParameter,
        },
    Boolean(source?.root),
  );
}

/** A folder of the landing storage, for files copied as they are. */
export function landingFilesDataset(shared: Shared, landing: string, http = false): Data {
  const result = binaryDataset(http ? shared.landingHttp : shared.landingFiles, shared.landing, {
    type: "AzureBlobFSLocation",
    fileSystem: parseLanding(landing).fileSystem,
    folderPath: folderParameter,
    ...(http && { fileName: { value: "@dataset().file", type: "Expression" } }),
  });
  if (http)
    (result.properties as Data).parameters = {
      folder: { type: "string" },
      file: { type: "string", defaultValue: "" },
    };
  return result;
}

function binaryDataset(name: string, service: string, location: Data, root = false): Data {
  return {
    name,
    properties: {
      type: "Binary",
      linkedServiceName: reference(service, "LinkedServiceReference"),
      parameters: { folder: { type: "string" }, ...(root && { root: { type: "string" } }) },
      typeProperties: { location },
    },
  };
}

/** A binary copy per table, all in one pipeline per share. */
export function filesPipeline(
  model: ResolvedModel,
  group: FilesGroup,
  shared: Shared,
  name: string,
): Data {
  return {
    name,
    properties: {
      activities: group.tables.map((table) => filesActivity(table, group, shared)),
      parameters: { windowStart: { type: "string" }, windowEnd: { type: "string" } },
      annotations: [`Generated by Ingestron from the ${model.project.id} definitions`],
    },
  };
}

/** A window time as the file filter takes it: UTC, YYYY-MM-DDTHH:mm:ssZ. */
const windowTime = (name: string) =>
  `@{formatDateTime(pipeline().parameters.${name}, 'yyyy-MM-dd''T''HH:mm:ss''Z''')}`;

/** Files changed in the window, unless every file is copied. */
function windowFilter(mode: unknown): Data {
  if (mode === "all") return {};
  return {
    modifiedDatetimeStart: windowTime("windowStart"),
    modifiedDatetimeEnd: windowTime("windowEnd"),
  };
}

function filesActivity(table: ResolvedTable, group: FilesGroup, shared: Shared): Data {
  const ingest = table.ingest!;
  const { path } = parseLanding(String(ingest.settings.landing));
  const object = ingest.object.replace(/\/+$/, "");
  return {
    name: resourceName(table, "copy_activity", `copy_${table.name}`),
    type: "Copy",
    inputs: [
      {
        ...reference(group.dataset, "DatasetReference"),
        parameters: nativeFileParameters(group.connection.connector, object),
      },
    ],
    outputs: [
      {
        ...reference(
          group.connection.connector === "http" ? shared.landingHttp : shared.landingFiles,
          "DatasetReference",
        ),
        parameters: {
          folder: [path, object].filter((part) => part !== "").join("/"),
          ...(group.connection.connector === "http" && { file: ingest.settings.files }),
        },
      },
    ],
    typeProperties: {
      source: binarySource(table),
      sink: {
        type: "BinarySink",
        storeSettings: { type: "AzureBlobFSWriteSettings", copyBehavior: "PreserveHierarchy" },
      },
    },
  };
}

function binarySource(table: ResolvedTable): Data {
  const ingest = table.ingest!;
  const options = (ingest.settings.source_options ?? {}) as Data;
  return {
    type: "BinarySource",
    storeSettings:
      ingest.connection.connector === "http"
        ? {
            type: "HttpReadSettings",
            requestMethod: options.request_method ?? "GET",
            ...(options.request_body !== undefined && { requestBody: options.request_body }),
          }
        : {
            type:
              fileStores.find((item) => item.id === ingest.connection.connector)?.read ??
              "FileServerReadSettings",
            recursive: true,
            wildcardFileName: ingest.settings.files,
            ...windowFilter(ingest.settings.mode),
          },
  };
}
