// The design settings in the generated resources: the Copy activity policy,
// the factory folder, annotations, and a description on everything.
import { describe, expect, it } from "vitest";
import { base, generate, json } from "./erp.js";
import { tableProject } from "./table-project.js";

const withDesign = (lines: string[], standard = base["standard.yaml"]!) =>
  standard.replace(
    "      start: 2026-10-01T00:00:00Z\n",
    `      start: 2026-10-01T00:00:00Z\n${lines.map((line) => `      ${line}`).join("\n")}\n`,
  );

const built = (lines: string[]) => {
  const { result, files } = generate({ "standard.yaml": withDesign(lines) });
  expect(result.diagnostics).toEqual([]);
  return files;
};

const s3 = {
  "standard.yaml": base["standard.yaml"]!.replace("adf-copy:", "adf-files:\n      format: csv"),
  "erp.yaml":
    "apiVersion: ingestron.io/v1\nkind: Connection\nid: erp\nconnector: amazon-s3\nconnectivity: private\nsettings:\n  access_key: synthetic-access\n  secret_key: ${secret:s3-key}\n",
  "flow.yaml": base["flow.yaml"]!.replace("erp.dbo.Invoices", "sales/orders"),
};

describe("the Copy activity policy", () => {
  it("is written from activity, in ADF's form", () => {
    const files = built(["activity: { retries: 2, retry_interval: 60, timeout: 120 }"]);
    const copy = json(files, "pipeline/pl_erp_erp.json").properties.activities[0];
    expect(copy.policy).toEqual({ timeout: "0.02:00:00", retry: 2, retryIntervalInSeconds: 60 });
  });

  it("writes days and only the keys that are set", () => {
    const files = built(["activity: { timeout: 1500 }"]);
    const copy = json(files, "pipeline/pl_erp_erp.json").properties.activities[0];
    expect(copy.policy).toEqual({ timeout: "1.01:00:00" });
  });

  it("is left out without activity", () => {
    const copy = json(built([]), "pipeline/pl_erp_erp.json").properties.activities[0];
    expect(copy).not.toHaveProperty("policy");
  });

  it("applies to files copied as they are", () => {
    const { result, files } = generate({
      ...s3,
      "standard.yaml": withDesign(["activity: { retries: 3 }"], s3["standard.yaml"]),
    });
    expect(result.diagnostics).toEqual([]);
    const copy = json(files, "pipeline/pl_erp_erp.json").properties.activities[0];
    expect(copy.policy).toEqual({ retry: 3 });
  });
});

describe("the factory's folders and annotations", () => {
  it("files the pipelines and datasets in the folder", () => {
    const files = built(["folder: ingestron/${project.id}"]);
    const foldered = Object.entries(files).filter(([path]) => /^(pipeline|dataset)\//.test(path));
    expect(foldered.length).toBeGreaterThan(2);
    for (const [path] of foldered)
      expect(json(files, path).properties.folder, path).toEqual({ name: "ingestron/erp" });
    expect(json(files, "linkedService/ls_erp_landing.json").properties).not.toHaveProperty(
      "folder",
    );
  });

  it("adds annotations after Ingestron's own", () => {
    const files = built(["annotations: [erp, finance]"]);
    expect(json(files, "pipeline/pl_erp_erp.json").properties.annotations).toEqual([
      "Generated by Ingestron from the erp definitions",
      "erp",
      "finance",
    ]);
  });

  it("must be the same for every ADF table", () => {
    const flow =
      "apiVersion: ingestron.io/v1\nkind: Flow\nid: erp\nsource: erp\ntables:\n  invoices: { object: erp.dbo.Invoices, contract: invoices }\n  credits: { object: erp.dbo.Credits, contract: invoices, ingest: { with: { folder: other } } }\n";
    const { result } = generate({
      "standard.yaml": withDesign(["folder: ingestron"]),
      "flow.yaml": flow,
    });
    expect(result.diagnostics.map((item) => item.message).join("\n")).toContain(
      "every ADF table must use the same folder",
    );
  });
});

describe("descriptions", () => {
  const described = (files: Record<string, string>) => {
    const pipelines = Object.keys(files).filter((path) => path.startsWith("pipeline/"));
    expect(pipelines.length).toBeGreaterThan(0);
    for (const path of pipelines) {
      const pipeline = json(files, path);
      expect(pipeline.properties.description, path).toMatch(/\w/);
      for (const activity of pipeline.properties.activities)
        expect(activity.description, `${path} ${activity.name}`).toMatch(/\w/);
    }
  };

  it("describe every pipeline and Copy activity", () => {
    const files = built([]);
    described(files);
    expect(json(files, "pipeline/pl_erp_erp.json").properties.activities[0].description).toBe(
      "Copies erp.dbo.Invoices to landing as Parquet.",
    );
  });

  it("describe native and file copies", () => {
    const native = tableProject("rest", "  url: https://source.example.test", "orders");
    described(generate(native).files);
    described(generate(s3).files);
  });
});

describe("review fixes", () => {
  it("lets each pipeline have its own annotations", () => {
    const hr = base["erp.yaml"]!.replace("id: erp", "id: hr");
    const { result, files } = generate({
      "hr.yaml": hr,
      "flow.yaml":
        "apiVersion: ingestron.io/v1\nkind: Flow\nid: erp\nsource: erp\ningest: { with: { annotations: [finance] } }\ntables:\n  invoices: { object: erp.dbo.Invoices, contract: invoices }\n",
      "hr-flow.yaml":
        "apiVersion: ingestron.io/v1\nkind: Flow\nid: hr\nsource: hr\ningest: { with: { annotations: [people] } }\ntables:\n  staff: { object: hr.dbo.Staff, contract: invoices }\n",
    });
    expect(result.diagnostics).toEqual([]);
    expect(json(files, "pipeline/pl_erp_erp.json").properties.annotations).toContain("finance");
    expect(json(files, "pipeline/pl_erp_hr.json").properties.annotations).toContain("people");
    expect(json(files, "pipeline/pl_erp_hr.json").properties.annotations).not.toContain("finance");
  });

  it("still needs one folder for the project", () => {
    const flow =
      "apiVersion: ingestron.io/v1\nkind: Flow\nid: erp\nsource: erp\ntables:\n  invoices: { object: erp.dbo.Invoices, contract: invoices }\n  credits: { object: erp.dbo.Credits, contract: invoices, ingest: { with: { folder: other } } }\n";
    const { result } = generate({
      "standard.yaml": withDesign(["folder: ingestron"]),
      "flow.yaml": flow,
    });
    expect(result.diagnostics.map((item) => item.message).join("\n")).toContain(
      "every ADF table must use the same folder",
    );
  });

  it("names the table each ForEach copy ran for", () => {
    const files = built(["pattern: foreach"]);
    const copy = json(files, "pipeline/pl_erp_erp.json").properties.activities[0].typeProperties
      .activities[0];
    expect(copy.userProperties).toEqual([{ name: "table", value: "@item().table" }]);
  });
});
